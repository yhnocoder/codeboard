// Writes the icon path tables in packages/board/src/ui/icons.tsx from icons.src.mjs.
// Usage: node tools/icons/gen.mjs   (then node tools/icons/check.mjs)
//        node tools/icons/gen.mjs --check   writes nothing; exits 1 if the tables in icons.tsx / glyphs.tsx are not what gen.mjs would write (hand edits)
import * as fs from "node:fs";
import * as path from "node:path";
import { ICONS, MD_ICONS, STICKERS, STICKER_BOX } from "./icons.src.mjs";
import { xform } from "./shapes.mjs";

const CHECK = process.argv.includes("--check");
const stale = [];
const write = (f, text) => {
  if (!CHECK) fs.writeFileSync(f, text);
  else if (fs.readFileSync(f, "utf8") !== text) stale.push(path.relative(root, f));
};
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../..");
const file = path.join(root, "packages/board/src/ui/icons.tsx");
const rows = (set, k) =>
  Object.entries(set)
    .filter(([, v]) => v[k])
    .map(([n, v]) => `  ${n}: "${v[k]}", // ${v[2]}`)
    .join("\n");
const put = (src, v, body, f) => {
  const re = new RegExp(`(const ${v}: Record<string, string> = \\{\\n)[\\s\\S]*?(\\n\\};)`);
  if (!re.test(src)) throw new Error(`no table ${v} in ${path.relative(root, f)}`);
  return src.replace(re, (_, a, b) => a + body + b);
};
// the board's icons (stroke table P and fill table F), and the Markdown editor's toolbar and find bar icons (strokes only)
write(file, put(put(fs.readFileSync(file, "utf8"), "P", rows(ICONS, 0), file), "F", rows(ICONS, 1), file));
console.log(`icons.tsx: ${Object.keys(ICONS).length} icons`);
const mdFile = path.join(root, "packages/markdown/src/ui/icons.ts");
if (Object.values(MD_ICONS).some((v) => v[1])) throw new Error("MD_ICONS: the Markdown toolbar icons are strokes only");
write(mdFile, put(fs.readFileSync(mdFile, "utf8"), "P", rows(MD_ICONS, 0), mdFile));
console.log(`markdown ui/icons.ts: ${Object.keys(MD_ICONS).length} icons`);

// sticker built-ins: replace the d / fill of each BUILTIN row in glyphs.tsx
const gfile = path.join(root, "packages/board/src/stickers/glyphs.tsx");
let g = fs.readFileSync(gfile, "utf8");
for (const [name, v] of Object.entries(STICKERS)) {
  const re = new RegExp(`(\\{ name: "${name}", [^\\n]*?), (?:d|fill): "[^"]*"( \\})`);
  if (!re.test(g)) throw new Error(`no BUILTIN row for ${name}`);
  const key = v.fill ? "fill" : "d",
    d = xform(v.fill ?? v.d, STICKER_BOX.s, STICKER_BOX.o, STICKER_BOX.o);
  g = g.replace(re, (_, a, b) => `${a}, ${key}: "${d}"${b}`);
}
write(gfile, g);
console.log(`glyphs.tsx: ${Object.keys(STICKERS).length} stickers`);
if (CHECK && stale.length) {
  console.error(`not generated by tools/icons/gen.mjs (run it, or edit icons.src.mjs instead): ${stale.join(", ")}`);
  process.exit(1);
}
