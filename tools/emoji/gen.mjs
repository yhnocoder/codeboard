// Writes packages/markdown/src/emoji-data.ts (GitHub's shortcodes, name → emoji) from the gemoji package.
// Usage: node tools/emoji/gen.mjs   after bumping gemoji; packages/markdown/test/emoji.test.ts fails while the table is stale
import * as fs from "node:fs";
import * as path from "node:path";
import { createRequire } from "node:module";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../..");
const md = path.join(root, "packages/markdown");
const entry = createRequire(path.join(md, "package.json")).resolve("gemoji");
const { gemoji } = await import(entry);
const { version } = JSON.parse(fs.readFileSync(path.join(path.dirname(entry), "package.json"), "utf8"));
const rows = gemoji.flatMap((g) => g.names.map((n) => `${JSON.stringify(n)}:${JSON.stringify(g.emoji)}`));
const text = `// Generated by tools/emoji/gen.mjs from gemoji ${version}. Do not edit.
export const GEMOJI: Record<string, string> = {${rows.join(",")}};
`;
fs.writeFileSync(path.join(md, "src/emoji-data.ts"), text);
console.log(`emoji-data.ts: ${rows.length} names`);
