import { build, context } from "esbuild";
import { execFileSync } from "node:child_process";
import { copyFileSync, cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

// Files the bundle loads at run time are copied from the packages that use them, so they are the versions those packages were
// written against: the tree-sitter runtime and grammars (Python, Rust; C / C++ / CUDA share tree-sitter-cuda) that
// @codeboard/analysis loads with initAnalysis(dist), ELK from @codeboard/core, and the board's own build (media/board)
const require = createRequire(import.meta.url);
const fromAnalysis = createRequire(require.resolve("@codeboard/analysis"));
const fromCore = createRequire(require.resolve("@codeboard/core"));
const wasmDir = dirname(fromAnalysis.resolve("@vscode/tree-sitter-wasm/wasm/tree-sitter.wasm"));
mkdirSync("dist", { recursive: true });
for (const f of ["tree-sitter.wasm", "tree-sitter-python.wasm", "tree-sitter-rust.wasm"]) copyFileSync(join(wasmDir, f), join("dist", f));
const cudaWasm = fromAnalysis.resolve("@yhnocoder/tree-sitter-cuda/tree-sitter-cuda.wasm");
copyFileSync(cudaWasm, join("dist", "tree-sitter-cuda.wasm"));
// MIT 许可要求随附声明（tree-sitter-cpp 和 tree-sitter-cuda 的作者都在里面）
copyFileSync(join(dirname(cudaWasm), "LICENSE"), join("dist", "LICENSE-tree-sitter-cuda.txt"));
// ELK（Tidy Up 的排版）放在 dist/elk.js，第一次 Tidy Up 才 require：打进 extension.js 的话，插件每次启动都要多解析 3.5 MB（约 80 ms）
copyFileSync(fromCore.resolve("elkjs/lib/elk.bundled.js"), join("dist", "elk.js"));
// The webview loads the board's build from media/board (npm run build builds @codeboard/board first)
const boardDist = join(dirname(require.resolve("@codeboard/board/package.json")), "dist");
for (const f of ["board.js", "boot.js"])
  if (!existsSync(join(boardDist, f))) throw new Error(`${boardDist}/${f} is missing: build @codeboard/board first`);
rmSync("media/board", { recursive: true, force: true });
cpSync(boardDist, "media/board", { recursive: true });
const elkApart = { name: "elk-apart", setup: (b) => b.onResolve({ filter: /^elkjs\// }, () => ({ path: "./elk.js", external: true })) };

// 构建自哪个提交（Copy Diagnostics 里显示）：正好在发版 tag v<version> 上是正式版，什么都不加；否则写 "dev <短 commit>"，有没提交的改动再加 "dirty"
function buildId() {
  const run = (...a) => { try { return execFileSync("git", a, { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim(); } catch { return ""; } };
  const head = run("rev-parse", "--short", "HEAD");
  if (!head) return "";
  const { version } = JSON.parse(readFileSync("package.json", "utf8"));
  if (run("tag", "--points-at", "HEAD").split("\n").includes(`v${version}`)) return "";
  return `dev ${head}${run("status", "--porcelain", "--untracked-files=no") ? " dirty" : ""}`;
}

const opts = {
  entryPoints: ["src/extension.ts"],
  bundle: true,
  outfile: "dist/extension.js",
  platform: "node",
  format: "cjs",
  target: "node18",
  external: ["vscode"],
  plugins: [elkApart],
  sourcemap: true,
  logLevel: "info",
  // @codeboard/analysis 里 import.meta.resolve 只在没给 wasm 目录时用（vitest）；打包后用不到
  define: { "import.meta.resolve": "undefined", __CODEBOARD_BUILD__: JSON.stringify(buildId()) },
};
// package.json's contributes.commands / configuration are generated by src/contributes.ts (the host's command table, core's setting
// declarations). A local build writes them back; in CI (and with --check) a committed package.json that differs fails the build,
// since a build that rewrote it would make test/package.test.ts compare the file with itself
async function writeContributes(check) {
  const r = await build({ ...opts, entryPoints: ["src/contributes.ts"], outfile: undefined, write: false, sourcemap: false, logLevel: "warning" });
  const f = join(tmpdir(), `codeboard-contributes-${process.pid}.cjs`);
  writeFileSync(f, r.outputFiles[0].text);
  let gen;
  try { gen = require(f).contributes(); } finally { rmSync(f, { force: true }); }
  const text = readFileSync("package.json", "utf8"), pkg = JSON.parse(text);
  pkg.contributes.commands = gen.commands;
  pkg.contributes.configuration = gen.configuration;
  const out = `${JSON.stringify(pkg, null, 2)}\n`;
  if (out === text) return;
  if (check) {
    console.error("extensions/vscode/package.json: contributes.commands / configuration differ from what src/contributes.ts generates. Run npm run build and commit package.json.");
    process.exit(1);
  }
  writeFileSync("package.json", out);
  console.log("package.json: contributes.commands / configuration regenerated");
}

await writeContributes(!!process.env.CI || process.argv.includes("--check"));
// --contributes: only package.json (npm run check writes it before the unit tests read it, not halfway through them)
if (process.argv.includes("--contributes")) process.exit(0);
if (process.argv.includes("--watch")) await (await context(opts)).watch();
else await build(opts);
