// Writes Sources/CodeBoardMarkdown/Lexer/MarkedRules.swift: the GFM block and inline rules of the marked version the
// TypeScript Markdown package parses with, as JavaScript regex sources. The Swift lexer compiles them through JSRegex,
// which maps the few places where JavaScript and ICU regexes differ. Run after a marked upgrade:
//   node apps/macos/tools/markdown/rules.mjs
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { Lexer } from "marked";

const here = dirname(fileURLToPath(import.meta.url));
const version = createRequire(import.meta.url)("marked/package.json").version;
const out = join(here, "../../Sources/CodeBoardMarkdown/Lexer/MarkedRules.swift");

// a regex source as Swift raw-string pieces of at most 80 characters, joined with +
function literal(raw) {
  // control characters (a tab marked built its source with) as JavaScript escapes, which mean the same in a regex
  const src = raw.replace(/[\x00-\x1f\x7f]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, "0")}`);
  // enough # that neither the closing "# nor an escape \# can occur inside
  let hashes = "#";
  while (src.includes(`"${hashes}`) || src.includes(`\\${hashes}`)) hashes += "#";
  const parts = [];
  for (let i = 0; i < src.length; i += 80) parts.push(`${hashes}"${src.slice(i, i + 80)}"${hashes}`);
  return parts.join("\n      + ");
}
function group(name, rules, keys) {
  const lines = [`  enum ${name} {`];
  for (const k of keys) {
    const r = rules[k];
    if (!(r instanceof RegExp) || r.source === "(?:)") continue;
    const id = k.startsWith("_") ? k.slice(1) : k;
    lines.push(`    static let ${id} = JSRegex(\n      ${literal(r.source)},\n      flags: "${r.flags}")`);
  }
  lines.push("  }");
  return lines.join("\n");
}

const { block, inline } = Lexer.rules;
// rules marked keeps as a no-op (an object whose exec returns null) are left out: the lexer never calls them in GFM mode
const blockKeys = Object.keys(block.gfm).filter((k) => block.gfm[k] instanceof RegExp);
const inlineKeys = Object.keys(inline.gfm).filter((k) => inline.gfm[k] instanceof RegExp);
const swift = `// Generated by apps/macos/tools/markdown/rules.mjs from marked ${version} (GFM, no breaks): do not edit.
// These are the block and inline rules @yhnocoder/markdown tokenizes with; JSRegex reads them with JavaScript semantics.

// swift-format-ignore-file

enum MarkedRules {
  static let version = "${version}"

${group("Block", block.gfm, blockKeys)}

${group("Inline", inline.gfm, inlineKeys)}
}
`;
writeFileSync(out, swift);
console.log(`wrote ${out} (marked ${version}: ${blockKeys.length} block, ${inlineKeys.length} inline rules)`);
